/**
 * `npm run report:tests` — generates docs/test-report.md from ACTUAL runs:
 *   1. the Vitest suite (unit, integration, frontend) via its JSON reporter,
 *   2. every Test Lab fixture through the real runner (live local Ollama if configured & reachable).
 * Nothing in the report is hand-written pass/fail data.
 */
import { execSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { loadDotEnv, readConfig } from '../server/config';
import { Database } from '../server/db/database';
import { getActivePolicy } from '../server/policies';
import { DisabledProvider, MockProvider, OllamaProvider } from '../server/services/ai/providers';
import { CareRouteService } from '../server/services/careroute-service';
import { TEST_CASES } from '../server/testing/fixtures';
import { runTests, summariseResults } from '../server/testing/runner';

loadDotEnv();
const config = readConfig();
const started = new Date();

// 1) Vitest
const jsonFile = path.join(os.tmpdir(), `careroute-vitest-${Date.now()}.json`);
try {
  execSync(`npx vitest run --reporter=json --outputFile="${jsonFile}"`, { stdio: 'ignore' });
} catch {
  /* failures are read from the JSON below */
}
type VitestJson = { numTotalTests: number; numPassedTests: number; numFailedTests: number; numPendingTests: number; testResults: { name: string; assertionResults: { status: string; fullName: string }[] }[] };
const vitest = JSON.parse(fs.readFileSync(jsonFile, 'utf8')) as VitestJson;
const perFile = vitest.testResults.map((f) => ({
  file: path.relative(process.cwd(), f.name).replace(/\\/g, '/'),
  passed: f.assertionResults.filter((a) => a.status === 'passed').length,
  failed: f.assertionResults.filter((a) => a.status === 'failed').length,
}));
const failedNames = vitest.testResults.flatMap((f) => f.assertionResults.filter((a) => a.status === 'failed').map((a) => a.fullName));

// 2) Test Lab fixtures
const live = config.aiProvider === 'ollama' ? new OllamaProvider(config.ollamaBaseUrl, config.ollamaModel) : null;
const liveStatus = live ? await live.checkStatus() : null;
const results = await runTests('all', {
  sandbox: () => new CareRouteService(new Database(':memory:'), { aiProvider: new MockProvider('ok'), aiTimeoutMs: 1000, emergencyInstruction: 'x' }),
  liveProvider: live ?? new DisabledProvider(),
  aiTimeoutMs: Math.max(config.aiTimeoutMs, 60_000),
});
const summary = summariseResults(results);

const routeOf = (o: Record<string, unknown> | null | undefined) => (o && typeof o.route === 'string' ? o.route : o && typeof o.outcome === 'string' ? `outcome: ${o.outcome}` : '—');
const esc = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
const inputOf = (id: string) => {
  const tc = TEST_CASES.find((t) => t.id === id)!;
  const text = tc.input?.symptomDescription ?? JSON.stringify(tc.rawBody ?? '');
  if (!text.trim()) return text.length ? '(whitespace only)' : '(empty)';
  return esc(text.length > 90 ? `${text.slice(0, 90)}… (${text.length} chars)` : text);
};

const lines: string[] = [];
lines.push('# Test report', '');
lines.push(`> Generated by \`npm run report:tests\` on ${started.toISOString()} (${os.platform()} ${os.arch()}, Node ${process.version}). Policy \`${getActivePolicy().version}\`.`);
lines.push('> All results below come from actual executions. **Passing synthetic tests does not establish clinical safety.**', '');
lines.push('## 1. Automated suite (Vitest — unit, integration, frontend)', '');
lines.push(`**${vitest.numPassedTests} passed, ${vitest.numFailedTests} failed, ${vitest.numPendingTests} skipped — ${vitest.numTotalTests} total.**`, '');
lines.push('| Test file | Passed | Failed |', '|---|---:|---:|');
for (const f of perFile) lines.push(`| \`${f.file}\` | ${f.passed} | ${f.failed} |`);
if (failedNames.length) lines.push('', '**Failures:**', ...failedNames.map((n) => `- ${n}`));
lines.push('', 'Ollama is mocked in automated tests (`server/tests/ollama.test.ts`), so they never need a running model.', '');

lines.push('## 2. Synthetic routing test cases (Test Lab fixtures)', '');
lines.push(`Executed against the real routing engine, AI boundary, schemas and workflow services. Live AI case: ${liveStatus ? `local Ollama \`${config.ollamaModel}\` — ${liveStatus.state}` : 'no local AI configured'}.`, '');
lines.push(`**Overall: ${summary.overall}** — ${summary.passed} passed, ${summary.failed} failed, ${summary.skipped} skipped, ${summary.criticalFailures} safety-critical failures (of ${summary.total}).`, '');
lines.push('| ID | Test | Synthetic input | Expected | Actual | Status | Safety-critical |', '|---|---|---|---|---|---|---|');
for (const r of results) {
  const status = r.status === 'passed' ? '✅ passed' : r.status === 'skipped' ? '⏭️ skipped' : r.criticalFailure ? '🛑 CRITICAL FAIL' : '❌ failed';
  lines.push(`| ${r.testId} | ${esc(r.title)} | ${inputOf(r.testId)} | ${routeOf(r.expected as Record<string, unknown>)} | ${routeOf(r.actual)} | ${status}${r.failureReason ? ` — ${esc(r.failureReason)}` : ''} | ${r.safetyCritical ? 'yes' : ''} |`);
}
const routed = results.filter((r) => r.status !== 'skipped' && typeof (r.expected as Record<string, unknown>).route === 'string' && typeof r.actual?.route === 'string');
const fn = routed.filter((r) => r.expected.route === 'EMERGENCY_GUIDANCE' && r.actual!.route !== 'EMERGENCY_GUIDANCE').length;
const fp = routed.filter((r) => r.expected.route !== 'EMERGENCY_GUIDANCE' && r.actual!.route === 'EMERGENCY_GUIDANCE').length;
lines.push('', '### Route evaluation', '');
lines.push(`Denominator: ${routed.length} executed cases that specify an expected route.`, '');
lines.push(`- Correctly routed: ${routed.filter((r) => r.expected.route === r.actual!.route).length} / ${routed.length}`);
lines.push(`- Emergency false negatives (under the demo policy): ${fn}`);
lines.push(`- Emergency false positives (under the demo policy): ${fp}`, '');
lines.push('## 3. End-to-end (Playwright)', '');
lines.push('Run separately with `npm run test:e2e` (starts isolated servers on ports 3101/5174 with a throwaway database and AI disabled). See the README for the latest recorded result.', '');
lines.push('## 4. Limitations', '');
lines.push('- Fixtures are synthetic and written by the project team against an illustrative, non-validated policy; they test system behaviour, not clinical accuracy.');
lines.push('- Phrase matching (with negation/history heuristics and typo tolerance) cannot understand every paraphrase; unrecognised requests fall back to human review rather than routine.');
lines.push('- The live local-AI case depends on Ollama running with the configured model; its output can vary between model versions.');

fs.writeFileSync('docs/test-report.md', lines.join('\n') + '\n');
console.log(`Wrote docs/test-report.md — vitest ${vitest.numPassedTests}/${vitest.numTotalTests}, fixtures ${summary.passed} passed / ${summary.failed} failed / ${summary.skipped} skipped (${summary.overall}).`);
